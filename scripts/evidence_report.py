#!/usr/bin/env python3
"""Generate the evidence-level report: which prompts have actually been run.

The library's central honesty claim is that `operational` means *structurally
reviewed*, not *demonstrated*. That claim is only credible if it is measured.
This script reads `_meta/evidence.json` — the registry of runs that actually
happened and left a write-up — validates it against the catalog and the
filesystem, and generates `_meta/evidence-levels.md`.

It deliberately counts only recorded runs. A prompt that "seems fine" in use is
not evidence; a fixture, a transcript, and a defect list are.

Usage
-----
    python3 scripts/evidence_report.py            # print the summary
    python3 scripts/evidence_report.py --write    # regenerate _meta/evidence-levels.md
    python3 scripts/evidence_report.py --check    # exit 1 if the generated file is stale
                                              # or a published count has drifted

Exit codes: 0 ok, 1 stale or invalid registry.
"""

from __future__ import annotations

import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from validate_library import ROOT, is_archive, load  # noqa: E402

REGISTRY = os.path.join(ROOT, "_meta", "evidence.json")
OUTPUT = os.path.join(ROOT, "_meta", "evidence-levels.md")
REQUIRED = ("identifier", "title", "path", "date", "evaluator", "scope", "result", "record", "limitations")


def read_registry() -> tuple[list[dict], list[str]]:
    errors: list[str] = []
    if not os.path.exists(REGISTRY):
        return [], [f"{REGISTRY}: registry missing"]
    try:
        data = json.load(open(REGISTRY, encoding="utf-8"))
    except json.JSONDecodeError as exc:
        return [], [f"_meta/evidence.json: invalid JSON — {exc}"]
    entries = data.get("evaluations", [])
    for i, e in enumerate(entries):
        missing = [k for k in REQUIRED if not e.get(k)]
        if missing:
            errors.append(f"_meta/evidence.json: entry {i} ({e.get('identifier', '?')}) missing {missing}")
        for key in ("path", "record"):
            p = e.get(key)
            if p and not os.path.exists(os.path.join(ROOT, p)):
                errors.append(f"_meta/evidence.json: {e.get('identifier', '?')} {key} does not exist -> {p}")
    return entries, errors


def classify(entries: list[dict]) -> tuple[dict[str, dict], list[str]]:
    docs = load(ROOT)
    prompts = {d.identifier: d for d in docs if d.is_prompt and not is_archive(d.rel)}
    by_id: dict[str, dict] = {}
    problems: list[str] = []
    for e in entries:
        ident = e.get("identifier", "?")
        if ident not in prompts:
            problems.append(f"evidence for unknown identifier '{ident}' — the catalog has no such prompt")
            continue
        if ident in by_id:
            problems.append(f"duplicate evidence entry for '{ident}' — merge them, one prompt one record")
            continue
        if prompts[ident].rel.replace(os.sep, "/") != e.get("path", "").replace(os.sep, "/"):
            problems.append(
                f"{ident}: registry path {e.get('path')} does not match catalog path {prompts[ident].rel}"
            )
        by_id[ident] = e
    return by_id, problems


def counts(by_id: dict[str, dict]) -> dict[str, int]:
    docs = load(ROOT)
    prompts = [
        d for d in docs
        if d.is_prompt and not is_archive(d.rel) and d.rel.split(os.sep)[0] != "_meta"
    ]
    operational = [d for d in prompts if (d.maturity or "").lower() == "operational"]
    evaluated = [d for d in prompts if d.identifier in by_id]
    return {
        "prompts": len(prompts),
        "operational": len(operational),
        "evaluated": len(evaluated),
        "operational_evaluated": len([d for d in evaluated if (d.maturity or "").lower() == "operational"]),
        "operational_unevaluated": len(operational) - len([d for d in evaluated if (d.maturity or "").lower() == "operational"]),
    }


def render(by_id: dict[str, dict], c: dict[str, int]) -> str:
    pct = (100.0 * c["operational_evaluated"] / c["operational"]) if c["operational"] else 0.0
    lines = [
        "# Evidence Levels",
        "",
        "**Generated by `scripts/evidence_report.py` from `_meta/evidence.json`. Do not edit by hand.**",
        "CI fails if this file is stale, so the numbers below cannot drift from the registry.",
        "",
        "## What the maturity label means, measured",
        "",
        "| Claim | Count |",
        "|-------|------:|",
        f"| Prompt files in the library | {c['prompts']} |",
        f"| Labelled `operational` (structurally reviewed) | {c['operational']} |",
        f"| `operational` prompts with a recorded execution | {c['operational_evaluated']} |",
        f"| `operational` prompts with no recorded execution | {c['operational_unevaluated']} |",
        f"| Share of `operational` prompts demonstrated | {pct:.1f}% |",
        "",
        "`operational` means the artifact meets the authoring standard and survived a structural",
        "review against the quality rubric. It does **not** mean the prompt has been run against a",
        "real repository. Exactly one column above measures execution, and it is the small one.",
        "",
        "## Recorded executions",
        "",
    ]
    if by_id:
        lines += [
            "| Prompt | Date | Evaluator | Scope | Result | Record | Limitations |",
            "|--------|------|-----------|-------|--------|--------|-------------|",
        ]
        for ident in sorted(by_id):
            e = by_id[ident]
            lines.append(
                f"| `{ident}` {e.get('title', '')} | {e['date']} | {e['evaluator']} | "
                f"{e['scope']} | {e['result']} | [`{os.path.basename(e['record'])}`](../{e['record']}) | {e['limitations']} |"
            )
    else:
        lines.append("No executions recorded.")
    lines += [
        "",
        "## How to add an execution",
        "",
        "1. Run the prompt against a fixture or a real task, following it as written.",
        "2. Write up what happened: what the prompt contributed, where it was silent, what you changed.",
        "3. Add an entry to `_meta/evidence.json` with that write-up in `record`.",
        "4. `python3 scripts/evidence_report.py --write && python3 scripts/validate_library.py`.",
        "",
        "An execution by someone other than the prompt's author counts for more than one by its author;",
        "record which it was. A run that found no defects is evidence of usability, not of quality —",
        "say what it could not have detected.",
        "",
        "## Why this file exists",
        "",
        "Every release note in this repository states the operational count. Without a measured",
        "evidence column, that number reads as a quality claim it does not support. This file is the",
        "correction, and it is generated so that improving the number requires actually running prompts.",
        "",
    ]
    return "\n".join(lines)


def published_claims(c: dict[str, int]) -> list[str]:
    """Find hand-written copies of the ratio that no longer match the registry.

    The generated file cannot drift, because `--check` compares it byte for byte.
    The prose that quotes it can, and did: the README, the quickstart, the status
    page and the publication documents each restated "14 of 228" while the
    registry had moved to 17. A reader trusts the prose, not the generator, so
    the number that is easiest to read is the one that has to be checked.

    Dated records are exempt: `_meta/empirical-evaluation-*.md`, `CHANGELOG.md`
    and `_meta/review-log.md` say what was true when they were written, and
    correcting them would be rewriting history. A zeroth count is skipped too:
    it is only ever used for the independent-run figure, which is a different
    number that happens to share the denominator.

    Percentages are not scanned. The same files quote the composition figure and
    the link figure, so a bare percentage cannot be attributed to this ratio
    without guessing.
    """
    import re
    pattern = re.compile(r"\b(\d+) of " + str(c["operational"]) + r"\b")
    findings: list[str] = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [d for d in dirnames if not d.startswith(".") and not is_archive(d)]
        for name in filenames:
            if not name.endswith(".md") or name in ("CATALOG.md", "evidence-levels.md"):
                continue
            path = os.path.join(dirpath, name)
            rel = os.path.relpath(path, ROOT)
            if (rel.startswith(os.path.join("_meta", "empirical-evaluation-"))
                    or rel in ("CHANGELOG.md", os.path.join("_meta", "review-log.md"))):
                continue
            for lineno, line in enumerate(open(path, encoding="utf-8", errors="replace"), 1):
                # The denominator is shared with other measurements: "165 of 235
                # prompts are skeleton" is a true sentence about a different
                # thing, and flagging it was the first false positive this scan
                # produced. Requiring the line to be about execution keeps the
                # check honest in both directions.
                if not any(word in line.lower() for word in ("execut", "record", "run")):
                    continue
                for m in pattern.finditer(line):
                    if int(m.group(1)) not in (0, c["operational_evaluated"]):
                        findings.append(
                            f"{rel}:{lineno}: says {m.group(0)}; the registry says "
                            f"{c['operational_evaluated']} of {c['operational']}"
                        )
    return findings


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="regenerate _meta/evidence-levels.md")
    ap.add_argument("--check", action="store_true", help="exit 1 if the generated file is stale")
    args = ap.parse_args()

    entries, errors = read_registry()
    by_id, problems = classify(entries)
    errors.extend(problems)
    if errors:
        for e in errors:
            print(f"ERROR   {e}", file=sys.stderr)
        return 1

    c = counts(by_id)
    text = render(by_id, c)

    if args.write:
        with open(OUTPUT, "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"Evidence report written: {c['operational_evaluated']}/{c['operational']} operational prompts executed "
              f"({100.0 * c['operational_evaluated'] / c['operational'] if c['operational'] else 0:.1f}%)")
        return 0

    if args.check:
        current = open(OUTPUT, encoding="utf-8").read() if os.path.exists(OUTPUT) else ""
        if current != text:
            print("ERROR   _meta/evidence-levels.md is stale. Run: python3 scripts/evidence_report.py --write",
                  file=sys.stderr)
            return 1
        stale = published_claims(c)
        if stale:
            for s in stale:
                print(f"ERROR   {s}", file=sys.stderr)
            print("ERROR   published counts drifted from the registry", file=sys.stderr)
            return 1
        print("Evidence report is current.")
        return 0

    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
